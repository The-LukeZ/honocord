import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import type { Plugin } from "vite";
import { parse } from "yaml";

const SOURCE = resolve(import.meta.dirname, "../src/lib/built-with.yaml");
const OUTPUT = resolve(import.meta.dirname, "../src/lib/generated/built-with.ts");
const FIELDS = ["title", "description", "link"] as const;

// Parse the YAML list, check every entry, and return the TypeScript module the page imports.
function render(): string {
  const data: unknown = parse(readFileSync(SOURCE, "utf8"));
  if (!Array.isArray(data)) throw new Error(`${SOURCE}: expected a list of bots`);
  const entries = data.map((entry: unknown, i) => {
    if (typeof entry !== "object" || entry === null) throw new Error(`${SOURCE}: entry ${i + 1} is not a mapping`);
    const record = entry as Record<string, unknown>;
    for (const field of FIELDS) {
      if (typeof record[field] !== "string" || !record[field]) {
        throw new Error(`${SOURCE}: entry ${i + 1} needs a non-empty "${field}" string`);
      }
    }
    // Keep only the known fields, in a fixed order.
    return Object.fromEntries(FIELDS.map((field) => [field, record[field]]));
  });

  return [
    "// Generated by plugins/built-with.ts from src/lib/built-with.yaml. Do not edit: change the YAML file instead.",
    "",
    "export interface BuiltWith {",
    "  title: string;",
    "  description: string;",
    "  link: string;",
    "}",
    "",
    `export const builtWith: BuiltWith[] = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
}

// Write only when the content changed, so an unchanged file does not trigger a reload.
function generate() {
  const code = render();
  if (existsSync(OUTPUT) && readFileSync(OUTPUT, "utf8") === code) return;
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, code);
}

/** Turns src/lib/built-with.yaml into src/lib/generated/built-with.ts, and regenerates it when the YAML changes in dev. */
export function builtWith(): Plugin {
  return {
    name: "honocord-docs:built-with",
    // `config` runs before anything imports the module, in dev, build and `svelte-kit sync`.
    config() {
      generate();
    },
    configureServer(server) {
      server.watcher.add(SOURCE);
      server.watcher.on("change", (file) => {
        if (resolve(file) !== SOURCE) return;
        try {
          generate();
        } catch (error) {
          server.config.logger.error(String(error));
        }
      });
    },
  };
}
